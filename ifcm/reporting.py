"""Generate LaTeX values from the current analysis summaries."""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "report"


def read_lidc(encoder: str) -> dict:
    path = ROOT / "results_lidc" / f"summary_{encoder}_lidc_cnn_split0.json"
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def metric(value: float, digits: int = 2) -> str:
    return f"{value:.{digits}f}"


def macro(name: str, value: str) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}\n"


def main() -> None:
    bio, dino, cnn = (read_lidc(name) for name in ("biomedclip", "dinov3", "cnn"))
    paired = cnn["attribution_bootstrap"]["paired_difference"]
    clustered = cnn["attribution_bootstrap"]["patient_clustered"]
    values = {
        "BioFindingAUC": metric(bio["concept_auc"]),
        "DinoFindingAUC": metric(dino["concept_auc"]),
        "CNNFindingAUC": metric(cnn["concept_auc"]),
        "BioDiagnosisAUC": metric(bio["auc: predicted findings + LLM panel edges [OURS]"]),
        "CNNDiagnosisAUC": metric(cnn["auc: predicted findings + LLM panel edges [OURS]"]),
        "BioBlackboxAUC": metric(bio["auc: black-box probe on embedding"]),
        "CNNBlackboxAUC": metric(cnn["auc: black-box CNN trained on malignancy"]),
        "BioAttrAUC": metric(bio["attr: perc_bern - know_flip"]),
        "DinoAttrAUC": metric(dino["attr: perc_bern - know_flip"]),
        "CNNAttrAUC": metric(cnn["attr: perc_bern - know_flip"]),
        "BioUncAUC": metric(bio["attr: 1-conf"]),
        "DinoUncAUC": metric(dino["attr: 1-conf"]),
        "CNNUncAUC": metric(cnn["attr: 1-conf"]),
        "CNNAttrGain": "+" + metric(paired["point"]),
        "CNNAttrGainLo": metric(paired["ci95"][0]),
        "CNNAttrGainHi": metric(paired["ci95"][1]),
        "CNNAttrTail": metric(paired["one_sided_p"], 3),
        "CNNClusterLo": metric(clustered["ci95"][0]),
        "CNNClusterHi": metric(clustered["ci95"][1]),
        "CNNClusterTail": metric(clustered["one_sided_p"], 3),
        "CNNPerceptionErrors": str(cnn["n_perception_errors"]),
        "BioTestErrors": str(bio["n_errors"]),
        "DinoTestErrors": str(dino["n_errors"]),
        "CNNTestErrors": str(cnn["n_errors"]),
        "BioPercReader": metric(bio["readers: perc_bern"][0]),
        "CNNPercReader": metric(cnn["readers: perc_bern"][0]),
        "BioKnowReader": metric(bio["readers: know_flip"][2]),
        "CNNKnowReader": metric(cnn["readers: know_flip"][2]),
    }
    (OUT / "generated_metrics.tex").write_text(
        "% Generated by python -m ifcm.reporting from current result summaries.\n"
        + "".join(macro(name, value) for name, value in values.items()), encoding="utf-8")

    rows = []
    for name, result in (("BiomedCLIP", bio), ("DINOv3", dino)):
        for i, (label, key) in enumerate((("Perceptual hesitancy", "perc_bern"),
                                          ("Knowledge hesitancy", "know_flip"),
                                          ("Plain uncertainty", "1-conf"))):
            measurements = result[f"readers: {key}"]
            cells = [metric(value) if value >= 0 else f"$-{metric(-value)}$" for value in measurements]
            rows.append(f"{name if i == 0 else ' '} & {label} & " + " & ".join(cells) + " " + chr(92) * 2)
        if name == "BiomedCLIP":
            rows.append(r"\midrule")
    (OUT / "generated_readers_rows.tex").write_text(
        "% Generated from current LIDC summary JSON files.\n"
        + "\\begin{tabular}{llccc}\n\\toprule\n"
        + "Encoder & Measure & Findings & Malignancy & Malignancy given findings \\\\\n"
        + "\\midrule\n" + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n", encoding="utf-8")
    print("Generated report/generated_metrics.tex and report/generated_readers_rows.tex")


if __name__ == "__main__":
    main()
